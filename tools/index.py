#!/usr/bin/env python3
"""Regenerate topics/<t>/index.md and topics/index.md deterministically (no LLM)."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *  # noqa: E402,F403


def _rel(frm, to):
    return os.path.relpath(to, frm).replace(os.sep, "/")


def _esc(s):
    return s.replace("|", "\\|")


def _questions(d):
    rows = []
    for p in sorted((d / "qa").glob("q-*.md")) if (d / "qa").is_dir() else []:
        meta, body = read_fm(p)
        rows.append((p, meta, get_section(body, "Question")))
    return rows


def _machine(d, key):
    cmp_ = versions(d / "llm", "compare") if (d / "llm").is_dir() else []
    if not cmp_:
        return None
    m = re.search(rf"^{key}:\s*(\d+)", cmp_[-1].read_text(encoding="utf-8"), re.M)
    return int(m.group(1)) if m else None


def _links_out(d):
    found = set()
    for p in (d / "human").rglob("*.md") if (d / "human").is_dir() else []:
        found.update(re.findall(r"\[\[([^\]|#]+)", strip_comments(p.read_text(encoding="utf-8"))))
    return sorted(found)


def topic_index(d):
    human, llm = d / "human", d / "llm"
    archived = (d / "log.md").exists() and "ARCHIVED" in (d / "log.md").read_text(encoding="utf-8")
    qs = _questions(d)
    out = [f"# {d.name}", "", "_Generated by tools/index.py. Do not edit._", ""]
    out.append(f"Status: **{'ARCHIVED' if archived else 'in progress'}**")
    oe, og = _machine(d, "OPEN_ERRORS"), _machine(d, "OPEN_GAPS")
    if oe is not None:
        out.append(f"Open errors (latest compare): **{oe}** · open gaps: **{og if og is not None else '?'}**")
    out += ["", "## Your artifacts", ""]
    if (human / "dump.md").exists():
        out.append(f"- Brain dump: [dump.md](human/dump.md)")
    ex = versions(human, "explain") if human.is_dir() else []
    if ex:
        out.append("- Explanations: " + " · ".join(f"[v{num(p)}](human/{p.name})" for p in ex))
    if (human / "FINAL.md").exists():
        out.append("- **Refined model: [FINAL.md](human/FINAL.md)**")
    out += ["", "## Agent reports", ""]
    gp = versions(llm, "gaps") if llm.is_dir() else []
    cp = versions(llm, "compare") if llm.is_dir() else []
    out.append("- Gap reports: " + (" · ".join(f"[v{num(p)}](llm/{p.name})" for p in gp) or "none yet"))
    out.append("- Comparisons: " + (" · ".join(f"[v{num(p)}](llm/{p.name})" for p in cp) or "none yet"))

    def table(rows):
        t = ["| id | by | status | due | question | from |", "|---|---|---|---|---|---|"]
        for p, m, q in rows:
            src = m.get("source", "")
            src_link = f"[{os.path.basename(src)}]({src})" if src else ""
            t.append(f"| [{m.get('id')}](qa/{p.name}) | {m.get('asked_by')} | {m.get('status')} | {m.get('due')} | {_esc(first_line(q))} | {src_link} |")
        return t

    needs = [r for r in qs if r[1].get("status") in ("open", "answered", "needs-work")]
    done = [r for r in qs if r[1].get("status") in ("restated", "solid")]
    due = [r for r in qs if str(r[1].get("due", "9999")) <= str(today())]
    out += ["", f"## Questions ({len(qs)} total, {len(due)} due today)", ""]
    out += ["### Needs your attention (no passing restatement yet)", ""]
    out += table(needs) if needs else ["_None._"]
    out += ["", "### Restated / solid", ""]
    out += table(done) if done else ["_None._"]
    links = _links_out(d)
    if links:
        out += ["", "## Links out (from your own writing)", ""] + [f"- [[{l}]]" for l in links]
    out.append("")
    return "\n".join(out), qs, archived


def regen():
    TOPICS.mkdir(exist_ok=True)
    rows = []
    for d in sorted(p for p in TOPICS.iterdir() if p.is_dir()):
        text, qs, archived = topic_index(d)
        (d / "index.md").write_text(text, encoding="utf-8")
        ex = versions(d / "human", "explain") if (d / "human").is_dir() else []
        due = sum(1 for _, m, _ in qs if str(m.get("due", "9999")) <= str(today()))
        unres = sum(1 for _, m, _ in qs if m.get("status") in ("open", "answered", "needs-work"))
        rows.append((d.name, f"v{num(ex[-1])}" if ex else "-", len(qs), unres, due, "archived" if archived else "active"))
    root = ["# Topics", "", "_Generated by tools/index.py._", "", "| topic | latest explanation | questions | unresolved | due today | state |", "|---|---|---|---|---|---|"]
    for r in rows:
        root.append(f"| [{r[0]}]({r[0]}/index.md) | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} |")
    root.append("")
    (TOPICS / "index.md").write_text("\n".join(root), encoding="utf-8")


if __name__ == "__main__":
    regen()
    print("indexes regenerated")
